"""ロープレの「進め方の切り口」コーチングを生成し、カンペ冒頭に出す用に保存する。

潜在ニーズを掘れない・話を繋げられないスタッフ向けに、
「この切り口で聞く→こう気づかせる→商材に繋げる」の導線を、カテゴリ×属性別に用意する。

- 既定は手書きの高品質コーチング（無料枠が無くてもすぐ使える）。
- --ai を付けると Gemini で表現を磨いて上書きする（1回・無料枠内）。

使い方:  python3 scripts/build_coaching_tips.py [--ai]
"""
from __future__ import annotations

import argparse
import json

from config import settings
from services import storage

CATS = ["導入", "コーティング", "エコカラット", "ダウンライト"]

# 手書きの切り口コーチング（キー="カテゴリ|属性"）。未検討＝営業が話のタネを撒く導線。
DEFAULT_TIPS = {
    "導入|未検討": (
        "『どんな暮らしにしたいか』を具体化させるのが最初の一歩。いきなり商材の話をしない。\n"
        "切り口例：『今のお住まいで“ここ不便だな”と感じることはありますか？』\n"
        "『ご家族構成は？（小さいお子様・ペット）』→ 生活の困りごとを引き出す。\n"
        "→ 出てきた困りごとを『それ、実は◯◯で解決できます』と“気づき”に変えて商材に繋げる。"
    ),
    "導入|検討済み": (
        "既に検討している内容を否定せず、まず具体的に聞いて土俵に乗る。\n"
        "切り口例：『どんな内容で見積もりを取られましたか？』『そこで気になっている点は？』\n"
        "→ 価格比較だけでなく“中身（耐久・保証・範囲）”の違いに話を移す。"
    ),
    "コーティング|未検討": (
        "『コーティング』の説明から入らない。まず床の“困りごと”を引き出す。\n"
        "切り口例：『お子様やペットはいらっしゃいますか？』『飲み物をこぼしたり、傷が気になったりしませんか？』\n"
        "→ 『実は今の新築フローリングは水に弱いんです』という“知らなかった気づき”を渡す。\n"
        "→ その不安の解決策としてコーティングを提示（機能の羅列にしない）。"
    ),
    "コーティング|検討済み": (
        "検討中のコーティング内容を聞いてから、まだ気づいていない観点を足す。\n"
        "切り口例：『種類は何で検討されてますか？』→ 耐久年数・保証・傷への強さの“違い”を可視化。\n"
        "→ 『同じ“コーティング”でも30年と5年で全然違う』と比較軸を変える。"
    ),
    "エコカラット|未検討": (
        "装飾ではなく“困りごと”から入る。玄関・水回りの匂い・湿気・カビは共感を得やすい。\n"
        "切り口例：『玄関の匂いや、下駄箱の湿気が気になったことはありませんか？』\n"
        "→ 『貼っておくと半永久的に効く』という気づきを渡し、装飾性は“おまけ”で添える。"
    ),
    "エコカラット|検討済み": (
        "検討場所を聞き、他に効く場所（トイレ・洗面・リビング）を提案で広げる。\n"
        "切り口例：『どこに検討されてますか？』→ 『実は匂いが気になる◯◯にも人気です』。\n"
        "→ グレードで価格が変わる仕組みを先に伝えて選びやすくする。"
    ),
    "ダウンライト|未検討": (
        "『照明を変えませんか』ではなく、暮らしの不便から入る。\n"
        "切り口例：『玄関やトイレで、電気の消し忘れ・手がふさがって困ることはありませんか？』\n"
        "→ 人感センサーで“自動で点く/消える”便利さに気づかせてから提案する。"
    ),
    "ダウンライト|検討済み": (
        "希望箇所を聞き、スイッチ交換とダウンライト交換のどちらが得かを一緒に整理する。\n"
        "切り口例：『どこに付けたいですか？灯数は？』→ 費用が変わるポイントを先に説明。"
    ),
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ai", action="store_true", help="Geminiで表現を磨いて上書き")
    args = ap.parse_args()

    tips = dict(DEFAULT_TIPS)

    if args.ai and settings.GEMINI_API_KEY:
        from google import genai

        gc = genai.Client(api_key=settings.GEMINI_API_KEY)
        prompt = (
            "あなたは新築マンションのリフォーム営業のトップコーチです。"
            "潜在ニーズを引き出せない後輩向けに、ロープレの『進め方の切り口』を作ります。\n"
            "弊社の前提：商談は内覧会の前。未検討のお客様は受け身なので、営業が"
            "暮らしの困りごとを引き出し“気づき”に変えてから商材に繋げる。説明先行はNG。\n"
            "重点商材：コーティング/エコカラット/ダウンライト。\n"
            "各『カテゴリ|属性』について、後輩がそのまま使える切り口を3〜4行で。"
            "『切り口例：』の具体的な問いかけを必ず含める。日本語。\n"
            "出力JSONのみ（キーは下記のまま）:\n"
            + json.dumps({k: "" for k in DEFAULT_TIPS}, ensure_ascii=False)
        )
        try:
            resp = gc.models.generate_content(
                model=settings.MINUTES_EXTRACT_MODEL,
                contents=prompt, config={"response_mime_type": "application/json"},
            )
            ai = json.loads(resp.text)
            for k in DEFAULT_TIPS:
                if isinstance(ai.get(k), str) and ai[k].strip():
                    tips[k] = ai[k].strip()
            print("✅ AIで表現を磨きました。")
        except Exception as e:  # noqa: BLE001
            print("⚠️ AI生成に失敗（既定の手書きを使用）:", str(e)[:120])

    storage.set_coaching_tips(tips)
    print(f"💾 コーチング {len(tips)} 件を保存しました。")
    print("例（コーティング|未検討）:\n", tips["コーティング|未検討"][:120])


if __name__ == "__main__":
    main()
