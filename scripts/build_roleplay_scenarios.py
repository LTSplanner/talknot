def _unit_rank(cat: str, title: str) -> tuple:
    keys = CATEGORY_UNIT_ORDER.get(cat)
    if keys:
        for i, k in enumerate(keys):
            if k in title:
                return (i, "")
        return (len(keys), title)
    return (0, title)

