"""評価の「2つの視点」（ナレッジ視点・目指す営業像視点）。

参考情報としてプロンプトに置くだけだと、AI が読み飛ばしても評価は通ってしまう。
そこで 2つの視点を評価結果の**必須の欄**にし、欠けていたら評価として受け付けない
（analyze_roleplay がやり直させ、それでも欠けたら失敗→定期実行で再評価）。

- 視点①ナレッジ：発言が、溜めてきた社内ナレッジ（商品・料金・FAQ・商談の知恵）と
  合っていたか。共有シートが読めないときは、下の控えの知識で評価し、
  knowledge_status="fallback" として画面で再評価をすすめる。
- 視点②目指す営業像：良い商談5点＋コンサルティングセールスの芯から見て、
  どこまでできて、どこでつまずき、その本当の原因はどこか。

出典（LTS-system 図書館・承認済み）：
  kn-0083 料金・サービス総合ナレッジ／kn-0108 AIロープレ設計思想（8段階診断）／
  kn-0109 コンサルティングセールス研修の型／kn-0126 営業哲学
"""
from __future__ import annotations

KNOWLEDGE_FULL = "full"          # 共有シートのナレッジで評価した
KNOWLEDGE_FALLBACK = "fallback"  # シートが読めず、控えの知識で評価した

# 目指す営業像（評価の芯）。シートに依存せず、毎回かならず評価に入る。
SALES_IDEAL = """\
# 目指す営業像（視点②の物差し。かならずこの物差しで評価する）
【良い商談の5点】
1) 背景理解：暮らし・家族・購入の経緯を自然に掴む
2) 自然なニーズ発掘：詰問せず、お客様自身に語らせて本音を拾う
3) 商材の最大拡張：拾ったニーズを重点商材へ自然に広げ、見積に最大限残す
4) 受注への前進：内覧会同行・次の打合せなど、次の一歩をその場で決める
5) 信頼のグリップ力：仲良しではなく「この人に任せたい」と思わせる誠実さ・プロ感
【コンサルティングセールスの芯】
- 特長 → 利点 → 価値 の順で伝える（機能の説明で止めない。価値は時間・お金で示す）
- ニーズの裏のニーズを取りに行く（言われた要望をそのまま満たして終わらない）
- 価格は価値で語る（値引き・相場の安さで勝負しない）
- 叶えられない要望には代わりを出す（「できません」で終わらせない）
- 「高い」は3種類（予算オーバー／価値が伝わっていない／なんとなく）を見極めてから返す
- 商談の段階（不信の払拭 → 信頼の開始 → 信頼を深める → ニーズを聴く → 価値を伝える
  → 決める）のどこでつまずいたかを見て、本当の原因はその手前の段の飛ばしにないかを見る
"""

# 控えの知識（共有シートが読めないときの最低限）。数字は kn-0083 の値だけ。
FALLBACK_KNOWLEDGE = """\
【控えの知識（共有シートを読み込めなかったため、最低限の社内知識だけで評価している）】
- 正式なお見積りは、内覧会で採寸してから確定する。施工は原則、引渡し前・家具の搬入前
- ハウスコーティング（3LDK標準・税込）：ウレタン8〜12万円（耐久約5〜20年）／
  シリコン20〜24万円（10〜15年）／UV・ガラス22〜28万円（20〜25年）／
  セラミックのセット約26.2〜27.6万円（14畳の3LDK・35年以上）
- セット商品は、床に加えて水廻りコーティングとクロスコーティングを含む
- エコカラット（㎡あたり・材料と施工込み）：H 29,500円／G 25,400円／S 21,800円／F 19,500円。
  8㎡以下は施工費15,000円が別途
- 内覧会同行：通常49,500円（税込）。次のどれか1つ以上のご注文で無料：
  ハウスコーティング小計6万円以上／エコカラット（何㎡でも）／窓ガラスフィルム6㎡以上／
  バルコニータイル6㎡以上／オーダー家具・システム収納20万円以上
- 割引（全室割・季節割など）は時期で変わるため、言い切らず社内確認とする
"""


def resolve_knowledge(knowledge_base: str | None) -> tuple[str, str]:
    """評価に渡すナレッジと、その状態（full / fallback）を返す。

    シートのナレッジが空（読めなかった）なら、控えの知識で必ず評価できるようにする。
    """
    text = (knowledge_base or "").strip()
    if text:
        return text, KNOWLEDGE_FULL
    return FALLBACK_KNOWLEDGE, KNOWLEDGE_FALLBACK


def lens_prompt_block(knowledge_status: str) -> str:
    """2つの視点で評価させる指示と、出力欄（lenses）の形。"""
    fallback_note = (
        "\n※今回は共有シートのナレッジを読み込めず、上の『控えの知識』だけで評価している。"
        "視点①は控えの知識で判断できる範囲に限り、判断できない点は無理に断定しない。\n"
        if knowledge_status == KNOWLEDGE_FALLBACK else ""
    )
    return f"""
{SALES_IDEAL}
# 【必須】2つの視点からの評価（lenses）
次の2つの視点で、かならず評価して JSON の "lenses" に書くこと。どちらかが空の評価は無効になる。
視点①ナレッジ：営業役の発言が、上の『弊社ナレッジ』（商品・料金・FAQ・商談の知恵）と
  合っていたか。数字・条件・施工の流れの誤り、ナレッジにある強み（言えば刺さる事実）の
  言い漏らしを、ターン（またはタイムスタンプ）と発言に紐づけて挙げる。
  問題が無ければ、合っていた点を根拠つきで挙げる（空にしない）。
視点②目指す営業像：上の『目指す営業像』の物差しで、できていたこと・つまずいたところと、
  その本当の原因（どの段・どの芯が欠けていたか）を書く。5点それぞれの到達度も付ける。
{fallback_note}
"lenses" の形：
"lenses": {{
  "knowledge": {{
    "verdict": "合っていた | 一部ずれ | ずれが大きい",
    "points": [
      {{"timestamp": "T1 または mm:ss", "said": "<営業役の発言>",
        "knowledge": "<照らしたナレッジ（要点）>", "comment": "<合っていた/ずれていた点と、こう言えば良い>"}}
    ],
    "comment": "<視点①のまとめ（1〜2文）>"
  }},
  "ideal": {{
    "steps": [
      {{"name": "背景理解 | 自然なニーズ発掘 | 商材の最大拡張 | 受注への前進 | 信頼のグリップ力",
        "status": "できた | 一部 | できていない | 出番なし", "note": "<根拠（ターン/時刻つき）>"}}
    ],
    "stumble": "<一番つまずいたところ（無ければ空文字）>",
    "root_cause": "<その本当の原因（どの段・どの芯が欠けていたか）>",
    "comment": "<視点②のまとめ（1〜2文）>"
  }}
}}
"""


class LensMissingError(ValueError):
    """評価結果に 2つの視点（lenses）が欠けている。"""


def require_lenses(data: dict) -> None:
    """2つの視点が埋まっているかを確かめる。欠けていたら LensMissingError。"""
    lenses = data.get("lenses") if isinstance(data, dict) else None
    if not isinstance(lenses, dict):
        raise LensMissingError("2つの視点（lenses）がありません")
    kn = lenses.get("knowledge")
    if not isinstance(kn, dict) or not (str(kn.get("comment") or "").strip() or kn.get("points")):
        raise LensMissingError("視点①ナレッジが空です")
    ideal = lenses.get("ideal")
    if not isinstance(ideal, dict) or not (str(ideal.get("comment") or "").strip()
                                           or ideal.get("steps")):
        raise LensMissingError("視点②目指す営業像が空です")
